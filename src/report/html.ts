/**
 * HTML reporter — a self-contained, styled report (no external assets).
 * Works in light and dark color schemes.
 */
import type { ScanResult, Finding, Severity } from '../types.js';

const SEV_META: Record<Severity, { label: string; color: string }> = {
  critical: { label: 'Critical', color: '#b4232a' },
  high: { label: 'High', color: '#d1453b' },
  medium: { label: 'Medium', color: '#c77d0a' },
  low: { label: 'Low', color: '#2d72d9' },
  info: { label: 'Info', color: '#6b7280' },
};

export function renderHtml(result: ScanResult): string {
  const s = result.stats.bySeverity;
  const findingsHtml = result.findings.length
    ? result.findings.map(renderCard).join('\n')
    : `<p class="empty">No findings. ✔</p>`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Aegis-DAST Report — ${esc(result.target)}</title>
<style>
  :root {
    --bg: #ffffff; --fg: #1a1a1a; --muted: #6b7280; --card: #f7f7f8;
    --border: #e5e7eb; --code-bg: #f0f0f2;
  }
  @media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
      --bg: #0f1115; --fg: #e6e6e6; --muted: #9aa0aa; --card: #171a21;
      --border: #272b33; --code-bg: #1d2129;
    }
  }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--fg);
    font: 15px/1.6 system-ui, -apple-system, Segoe UI, Roboto, sans-serif; }
  .wrap { max-width: 980px; margin: 0 auto; padding: 32px 16px 64px; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  .sub { color: var(--muted); font-size: 14px; margin: 0 0 24px; }
  .meta { display: flex; flex-wrap: wrap; gap: 8px 20px; color: var(--muted);
    font-size: 13px; margin-bottom: 24px; }
  .summary { display: flex; flex-wrap: wrap; gap: 10px; margin-bottom: 28px; }
  .pill { display: inline-flex; align-items: center; gap: 8px; padding: 8px 14px;
    border-radius: 999px; border: 1px solid var(--border); background: var(--card);
    font-size: 13px; font-weight: 600; }
  .dot { width: 10px; height: 10px; border-radius: 50%; display: inline-block; }
  .card { border: 1px solid var(--border); border-left-width: 4px; border-radius: 10px;
    background: var(--card); padding: 16px 18px; margin-bottom: 16px; }
  .card h3 { margin: 0 0 6px; font-size: 16px; }
  .tag { display: inline-block; font-size: 11px; font-weight: 700; letter-spacing: .03em;
    text-transform: uppercase; color: #fff; padding: 2px 8px; border-radius: 6px; margin-right: 8px; }
  .kv { color: var(--muted); font-size: 13px; margin: 2px 0; word-break: break-word; }
  .kv b { color: var(--fg); font-weight: 600; }
  code, pre { font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
    background: var(--code-bg); border-radius: 6px; }
  code { padding: 1px 5px; font-size: 12.5px; }
  pre { padding: 10px 12px; overflow-x: auto; font-size: 12.5px; margin: 8px 0 0;
    white-space: pre-wrap; word-break: break-word; }
  .ai { margin-top: 10px; padding: 8px 12px; border-radius: 8px;
    background: rgba(45,114,217,.08); border: 1px solid rgba(45,114,217,.25); font-size: 13px; }
  .refs a { color: var(--muted); font-size: 12px; margin-right: 10px; }
  .empty { color: var(--muted); font-size: 16px; }
  footer { margin-top: 40px; color: var(--muted); font-size: 12px;
    border-top: 1px solid var(--border); padding-top: 16px; }
</style>
</head>
<body>
<div class="wrap">
  <h1>Aegis-DAST Scan Report</h1>
  <p class="sub">${esc(result.target)}</p>
  <div class="meta">
    <span>Endpoints: <b>${result.stats.endpoints}</b></span>
    <span>Requests: <b>${result.requestCount}</b></span>
    <span>Duration: <b>${(result.durationMs / 1000).toFixed(1)}s</b></span>
    <span>AI engine: <b>${esc(result.aiProvider)}</b></span>
    <span>FPs suppressed: <b>${result.stats.suppressedFalsePositives}</b></span>
    <span>Generated: <b>${esc(result.finishedAt)}</b></span>
  </div>
  <div class="summary">
    ${(['critical', 'high', 'medium', 'low', 'info'] as Severity[])
      .map(
        (sev) =>
          `<span class="pill"><span class="dot" style="background:${SEV_META[sev].color}"></span>${SEV_META[sev].label}: ${s[sev]}</span>`,
      )
      .join('\n    ')}
  </div>
  ${findingsHtml}
  <footer>
    Generated by <b>Aegis-DAST</b> — an AI-augmented DAST scanner.
    Only scan systems you own or are authorized to test.
  </footer>
</div>
</body>
</html>`;
}

function renderCard(f: Finding): string {
  const meta = SEV_META[f.severity];
  const ai = f.aiReview
    ? `<div class="ai"><b>AI review (${esc(f.aiReview.provider)}):</b> ${esc(f.aiReview.verdict)} ·
       exploitability ${f.aiReview.exploitabilityScore.toFixed(2)}<br/>${esc(f.aiReview.rationale)}</div>`
    : '';
  const refs = f.references.length
    ? `<div class="refs">${f.references
        .map((r) => (r.startsWith('http') ? `<a href="${esc(r)}" rel="noreferrer">${esc(r)}</a>` : `<span class="refs">${esc(r)}</span>`))
        .join(' ')}</div>`
    : '';
  return `<div class="card" style="border-left-color:${meta.color}">
    <h3><span class="tag" style="background:${meta.color}">${meta.label}</span>${esc(f.title)}</h3>
    <div class="kv"><b>Rule:</b> <code>${esc(f.ruleId)}</code> · <b>Confidence:</b> ${esc(f.confidence)}</div>
    <div class="kv"><b>Location:</b> ${esc(f.evidence.method)} ${esc(f.evidence.url)}${
      f.evidence.param ? ` · <b>Param:</b> <code>${esc(f.evidence.param)}</code>` : ''
    }</div>
    <div class="kv">${esc(f.description)}</div>
    ${f.evidence.payload ? `<div class="kv"><b>Payload:</b> <code>${esc(f.evidence.payload)}</code></div>` : ''}
    ${f.evidence.snippet ? `<pre>${esc(f.evidence.snippet)}</pre>` : ''}
    <div class="kv"><b>Remediation:</b> ${esc(f.remediation)}</div>
    ${ai}
    ${refs}
  </div>`;
}

function esc(s: string): string {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
